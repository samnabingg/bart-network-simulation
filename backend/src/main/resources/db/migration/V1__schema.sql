-- Reference data for the BART network. Works on PostgreSQL and on H2 in PostgreSQL mode.

CREATE TABLE station (
    abbr          VARCHAR(4)   PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL,
    kind          VARCHAR(16)  NOT NULL CHECK (kind IN ('underground', 'elevated', 'surface')),
    platform      VARCHAR(8)   NOT NULL CHECK (platform IN ('island', 'side')),
    lat           DOUBLE PRECISION,
    lon           DOUBLE PRECISION,
    -- where lat/lon came from: BART's station API wins over the average of the entrances
    coord_source  VARCHAR(16)  NOT NULL DEFAULT 'none' CHECK (coord_source IN ('none', 'entrances', 'api')),
    address       VARCHAR(200),
    city          VARCHAR(80),
    updated_at    TIMESTAMP WITH TIME ZONE
);

CREATE TABLE transit_line (
    id                 VARCHAR(16) PRIMARY KEY,
    name               VARCHAR(40) NOT NULL,
    hex                VARCHAR(7)  NOT NULL,
    api_hex            VARCHAR(7)  NOT NULL,  -- the color BART's API reports, used to match live trains
    headway_min        INTEGER     NOT NULL CHECK (headway_min > 0),
    forward_direction  VARCHAR(5)  NOT NULL CHECK (forward_direction IN ('North', 'South')),
    demo_offset_sec    INTEGER     NOT NULL DEFAULT 0,
    display_order      INTEGER     NOT NULL UNIQUE
);

-- Stops in the line's forward direction.
CREATE TABLE line_stop (
    line_id       VARCHAR(16) NOT NULL REFERENCES transit_line (id) ON DELETE CASCADE,
    seq           INTEGER     NOT NULL,
    station_abbr  VARCHAR(4)  NOT NULL REFERENCES station (abbr),
    PRIMARY KEY (line_id, seq)
);
CREATE INDEX idx_line_stop_station ON line_stop (station_abbr);

-- Track centerline from BART's KML, one polyline per row, stored as a JSON array of [lon, lat].
CREATE TABLE track_segment (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seq     INTEGER NOT NULL,
    points  VARCHAR NOT NULL
);

CREATE TABLE station_entrance (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_abbr  VARCHAR(4)   NOT NULL REFERENCES station (abbr),
    name          VARCHAR(200) NOT NULL,
    lat           DOUBLE PRECISION NOT NULL,
    lon           DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_entrance_station ON station_entrance (station_abbr);
